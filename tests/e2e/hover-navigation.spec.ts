import {expect, test} from '@playwright/test';
import {mkdir} from 'node:fs/promises';
import AxeBuilder from '@axe-core/playwright';
import {installApiMocks} from './helpers';

const captures = 'outputs/advanced-motion-2026-10-13';

test('hover rails make room for content, leave with delay, and support keyboard escape', async ({page}) => {
  await page.setViewportSize({width:1440, height:1000});
  await installApiMocks(page, {signedIn:true});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/courses');
  await mkdir(captures, {recursive:true});
  const sidebar = page.locator('.sidebar-auto-slot');
  const aside = sidebar.locator('aside');
  const heading = page.getByRole('heading', {name:'课程中心', level:1, exact:true});
  await expect(sidebar).toHaveAttribute('data-expanded', 'false');
  await expect.poll(async () => (await aside.boundingBox())?.width).toBe(72);
  const initial = await heading.boundingBox();
  await page.screenshot({path:`${captures}/courses-folded-1440.png`});
  await aside.hover();
  await expect(sidebar).toHaveAttribute('data-expanded', 'true');
  await expect.poll(async () => (await aside.boundingBox())?.width).toBe(232);
  const expanded = await aside.boundingBox();
  expect((await heading.boundingBox())!.x).toBeGreaterThanOrEqual(expanded!.x + expanded!.width);
  expect((await heading.boundingBox())!.x).toBeGreaterThan(initial!.x);
  await sidebar.getByRole('link', {name:'论文研究', exact:true}).hover();
  await expect(sidebar).toHaveAttribute('data-expanded', 'true');
  await page.screenshot({path:`${captures}/app-navigation-expanded-1440.png`});
  await page.mouse.move(1100, 100);
  await expect(sidebar).toHaveAttribute('data-expanded', 'true');
  await expect(sidebar).toHaveAttribute('data-expanded', 'false');
  await expect.poll(async () => (await aside.boundingBox())?.width).toBe(72);
  await page.keyboard.press('Tab');
  // Focus the real rail link using a keyboard-originated focus, not a mouse click.
  await sidebar.getByRole('link', {name:'课程中心', exact:true}).focus();
  await expect(sidebar).toHaveAttribute('data-expanded', 'true');
  await expect.poll(async () => {
    const rail = await aside.boundingBox(); const title = await heading.boundingBox();
    return Boolean(rail && title && title.x >= rail.x + rail.width);
  }).toBe(true);
  await page.keyboard.press('Escape');
  await expect(sidebar).toHaveAttribute('data-expanded', 'false');
  await expect(sidebar.getByRole('button', {name:'展开或收起主导航'})).toBeFocused();

  const toggle = page.getByRole('button', {name:'课程目录', exact:true});
  const directory = page.getByRole('navigation', {name:'选择课程', exact:true});
  const sheet = page.locator('.course-overview');
  const sheetPosition = await sheet.boundingBox();
  await toggle.hover();
  await expect(toggle).toHaveAttribute('aria-expanded', 'true');
  await directory.getByRole('button', {name:'ECON-204 微观经济学', exact:true}).hover();
  expect((await sheet.boundingBox())?.x).toBe(sheetPosition?.x);
  await page.screenshot({path:`${captures}/course-directory-expanded-1440.png`, animations:'disabled'});
  await directory.getByRole('button', {name:'ECON-204 微观经济学', exact:true}).click();
  await expect(page.getByRole('heading', {name:'微观经济学', exact:true})).toBeVisible();
  await page.mouse.move(1100, 100);
  await expect(toggle).toHaveAttribute('aria-expanded', 'false');
  await expect(directory).toBeHidden();
  await toggle.focus();
  // Switch to keyboard modality before entering the disclosure.
  await page.keyboard.press('Tab');
  await page.keyboard.press('Shift+Tab');
  await expect(toggle).toHaveAttribute('aria-expanded', 'true');
  await page.keyboard.press('Tab');
  await expect(directory.getByRole('button').first()).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(toggle).toHaveAttribute('aria-expanded', 'false');
  await expect(toggle).toBeFocused();
  await page.goto('/dashboard');
  await expect(page.locator('.dashboard-loading')).toBeHidden();
  await expect(page.locator('.sidebar-auto-slot')).toHaveAttribute('data-expanded','false');
  expect(await page.locator('.sidebar-auto-slot a[aria-current="page"] svg').evaluate(element=>getComputedStyle(element).color)).toBe('rgb(255, 255, 255)');
  await page.screenshot({path:`${captures}/dashboard-folded-1440.png`, animations:'disabled'});
});

test('chapter rail keeps reading and answers intact, with reduced motion and narrow desktop access', async ({page}) => {
  await page.setViewportSize({width:900, height:900});
  await page.emulateMedia({reducedMotion:'reduce'});
  await installApiMocks(page, {signedIn:true});
  await page.goto('/courses/STAT-201/lesson-1');
  const marker = page.locator('.sidebar-nav-motion .motion-navigation-marker');
  await expect(marker).toBeVisible();
  expect(await marker.evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(48, 95, 206)');
  const answer = page.locator('[aria-labelledby="title-STAT-201-l1-q3"]').getByLabel('输入数值答案');
  await answer.fill('0.6');
  const chapter = page.getByRole('button', {name:'章节导航', exact:true});
  await chapter.hover();
  await expect(chapter).toHaveAttribute('aria-expanded','true');
  const directory = page.getByRole('navigation', {name:'课程内导航'});
  await expect(directory.getByRole('link', {name:'返回课程目录'})).toBeVisible();
  await expect(directory.locator('[aria-current="page"]')).toHaveAttribute('href','/courses/STAT-201/lesson-1');
  await expect.poll(() => page.locator('.course-navigation-rail').evaluate(element=>element.getAnimations({subtree:true}).length)).toBe(0);
  await mkdir(captures, {recursive:true});
  await page.screenshot({path:`${captures}/chapter-directory-expanded-900.png`, animations:'disabled'});
  await page.mouse.move(800, 50);
  await expect(chapter).toHaveAttribute('aria-expanded','false');
  await expect(answer).toHaveValue('0.6');
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth+1)).toBe(true);
  await chapter.hover();
  const next = directory.locator('a[href="/courses/STAT-201/lesson-2"]');
  await next.click();
  await expect(page).toHaveURL('/courses/STAT-201/lesson-2');
  await expect(page.getByRole('heading', {name:'学习目标', exact:true})).toBeVisible();
});

test('touch disclosures close outside, main drawer keeps its focus trap, and opened directories have no serious accessibility errors', async ({browser}) => {
  const context = await browser.newContext({viewport:{width:375,height:812}, hasTouch:true, isMobile:true});
  const page = await context.newPage();
  await page.emulateMedia({reducedMotion:'reduce'});
  await installApiMocks(page, {signedIn:true});
  await page.goto('/courses');
  await expect.poll(async () => {
    const sidebar = await page.locator('.app-sidebar').boundingBox();
    return Boolean(sidebar && sidebar.x + sidebar.width <= 0);
  }).toBe(true);
  const toggle = page.getByRole('button', {name:'课程目录', exact:true});
  await toggle.tap();
  await expect(toggle).toHaveAttribute('aria-expanded','true');
  await mkdir(captures, {recursive:true});
  await page.screenshot({path:`${captures}/course-directory-expanded-375.png`, animations:'disabled'});
  const audit = await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  expect(audit.violations.filter(v=>v.impact==='serious'||v.impact==='critical')).toEqual([]);
  await page.getByRole('heading', {name:'课程中心', level:1, exact:true}).tap();
  await expect(toggle).toHaveAttribute('aria-expanded','false');
  await page.getByRole('button', {name:'打开主导航', exact:true}).tap();
  const drawer = page.getByRole('complementary', {name:'应用导航'});
  await expect(drawer).toBeVisible();
  await page.keyboard.press('Shift+Tab');
  await expect(drawer.getByRole('link', {name:'返回 Acaora 工作台'})).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(drawer.getByRole('link', {name:'编辑个人资料'})).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', {name:'打开主导航', exact:true})).toBeFocused();
  await context.close();
});
