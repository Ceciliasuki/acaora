import { execFileSync } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const defaultOutput = fileURLToPath(new URL("../app/generated/build-version.ts", import.meta.url));
const shaPattern = /^[0-9a-f]{7,64}$/i;

export function resolveBuildCommit({ cwd = process.cwd(), env = process.env, runGit = execFileSync } = {}) {
  try {
    const commit = String(runGit("git", ["rev-parse", "HEAD"], {
      cwd,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    })).trim();
    if (shaPattern.test(commit)) return commit;
  } catch {
    // GitHub exposes GITHUB_SHA as a documented fallback when a checkout omits Git metadata.
  }

  const githubSha = env.GITHUB_SHA?.trim();
  if (githubSha && shaPattern.test(githubSha)) return githubSha;
  throw new Error("BUILD_COMMIT_UNAVAILABLE: git rev-parse HEAD did not return a valid Git SHA");
}

export async function generateBuildVersion({
  cwd = process.cwd(),
  env = process.env,
  outputPath = defaultOutput,
  commit = resolveBuildCommit({ cwd, env }),
  now = new Date(),
  environment = env.ACAORA_ENVIRONMENT?.trim()
    || (env.GITHUB_ACTIONS === "true" ? "ci" : env.NODE_ENV?.trim() || "production"),
} = {}) {
  if (!shaPattern.test(commit)) throw new Error(`BUILD_COMMIT_INVALID: ${commit}`);
  const buildTime = now.toISOString();
  const source = [
    "// Generated by scripts/generate-build-version.mjs. Do not edit or commit.",
    `export const BUILD_COMMIT = ${JSON.stringify(commit)};`,
    `export const BUILD_TIME = ${JSON.stringify(buildTime)};`,
    `export const BUILD_ENVIRONMENT = ${JSON.stringify(environment)};`,
    "",
  ].join("\n");
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, source, "utf8");
  return { commit, buildTime, environment, outputPath };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const result = await generateBuildVersion();
  process.stdout.write(`Generated build metadata for ${result.commit}\n`);
}
